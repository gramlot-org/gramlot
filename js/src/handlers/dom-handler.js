/**
 * The DOM of one Gramlot page and its correspondence with the Source (`gramlot.dom`).
 *
 * @module
 */
import {Handler} from './handler.js';

/** The DOM and its correspondence with the Source. */
export class DomHandler extends Handler {
    /** Size controls for the input device without rebuilding the page. */
    setTouchMode(mode = 'auto') {
        if (!['auto', 'on', 'off'].includes(mode)) throw new TypeError(`Invalid touch mode: ${mode}`);
        const root = this.gramlot.src.renderer.destination.ownerDocument.documentElement;
        if (mode === 'auto') root.removeAttribute('data-gramlot-touch');
        else root.setAttribute('data-gramlot-touch', mode);
    }
    /** Navigate the current document to an explicit HTTP(S) URL selected by page policy. */
    navigate(url) {
        if (typeof url !== 'string' || !url) throw new TypeError('Navigation requires an absolute HTTP(S) URL');
        const target = new URL(url);
        if (!['http:', 'https:'].includes(target.protocol) || target.username || target.password) {
            throw new TypeError('Navigation requires an HTTP(S) URL without credentials');
        }
        this.gramlot.src.renderer.destination.ownerDocument.defaultView.location.assign(target.href);
    }
    reference(descriptor) { return this.gramlot.src.renderer.references.resolve(descriptor); }
    /** The Source node of the nearest element generated by the renderer (§4.11bis). */
    getBaseSourceNode(domNode) { return this.gramlot.src.renderer.getBaseSourceNode(domNode); }
    /** The element built from a Source node, or null (§4.11bis). */
    getDomNode(sourceNode) { return this.gramlot.src.renderer.getDomNode(sourceNode); }
}
