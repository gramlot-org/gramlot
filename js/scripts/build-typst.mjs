/** Embed the optional compiler Worker, WASM and fonts for hosted/offline use. */
import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const result=await build({entryPoints:[fileURLToPath(new URL('../src/components/typst-worker.js',import.meta.url))],
    bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',minify:true,
    legalComments:'inline',metafile:true,loader:{'.wasm':'binary','.otf':'binary','.ttf':'binary'}});
const notice=await readFile(new URL('../../assets/typst-fonts/NOTICE',import.meta.url),'utf8');
await mkdir(new URL('../dist/',import.meta.url),{recursive:true});
await writeFile(new URL('../dist/typst-worker-source.js',import.meta.url),
    `// Generated by build-typst.mjs.\n/*! Font notices: ${notice.replaceAll('*/','* /')} */\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
export const typstInputs=result.metafile.inputs;
