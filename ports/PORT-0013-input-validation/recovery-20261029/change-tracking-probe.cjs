const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
if (!process.argv[2]) throw new Error('Pass the extracted legacy root.');
const dir = path.join(path.resolve(process.argv[2]), 'gnrjs/tests');
const source = fs.readFileSync(path.join(dir, 'item_formstore_record.test.js'), 'utf8');
const fixture = source.slice(0, source.indexOf("test('saving an untouched"));
const sandbox = {require, console, process, __dirname:dir};
vm.runInNewContext(fixture + '\nthis.makeStage = createStage;', sandbox);
const s = sandbox.makeStage();
const write = value => s.record.setItem('seats', value);
write(121); write(122);
const node = s.record.getNode('seats');
const changes = s.outer.getChangesLogger().getNodes();
assert.equal(node.attr._loadedValue, 120);
assert.equal(changes.length, 1);
assert.equal(changes[0].attr.from, 120);
assert.equal(changes[0].attr.to, 122);
const payload = s.outer.getFormChanges().getItem('record').getNode('seats');
assert.equal(payload.getValue(), 122);
assert.ok(String(payload.attr.oldValue).includes('120'));
console.log('120 → 121 → 122: baseline 120; one net change 120 → 122; save includes oldValue:', payload.attr.oldValue);
write(120);
assert.equal(s.outer.getChangesLogger().len(), 0);
assert.equal(Object.hasOwn(node.attr, '_loadedValue'), false);
console.log('Return to 120: net change and _loadedValue removed.');
s.record.setItem('temporary', 'draft');
s.record.popNode('temporary');
assert.equal(s.outer.getChangesLogger().len(), 0);
console.log('Insert then delete: no remaining net change.');
s.record.popNode('seats');
const deleted = s.outer.getChangesLogger().getNodes()[0];
assert.equal(Object.hasOwn(deleted.attr, 'from'), false);
console.log('Deletion log has path but no old subtree/value: insufficient on its own for undo.');
